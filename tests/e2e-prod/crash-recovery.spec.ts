import fs from 'node:fs';
import path from 'node:path';
import { expect, test, type Page } from '@playwright/test';

// Runs against the minified production build (playwright.prod.config.ts), Clerk mocked.

const BUDGET = 77123;

const NARRATIVE = {
  executiveSummary: 'A focused plan that puts most of the budget into the best performing channels.',
  operatorInsight: 'Shift spend gradually and watch the cost per customer weekly.',
  biggestRisk: 'Concentration in a single channel could raise costs.',
  firstCheckIn: 'After week one, compare cost per customer against the target.',
};

async function seed(page: Page) {
  await page.addInitScript((budget) => {
    if (!localStorage.getItem('mediaplan-store-v2')) {
      localStorage.setItem(
        'mediaplan-store-v2',
        JSON.stringify({ state: { hasCompletedOnboarding: true, totalBudget: budget }, version: 9 })
      );
    }
  }, BUDGET);
}

async function mockGateway(page: Page, body: unknown) {
  await page.route('**/api/ai-gateway', (route) =>
    route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) })
  );
}

const storedBudget = (page: Page) =>
  page.evaluate(() => JSON.parse(localStorage.getItem('mediaplan-store-v2') ?? '{}').state?.totalBudget);

test('a stale Report chunk (HTML served for the old asset) shows a recoverable error, not a dead app', async ({ page }) => {
  await seed(page);
  await mockGateway(page, { text: JSON.stringify(NARRATIVE), toolCalls: [], raw: [] });
  // What Vercel used to return for a missing hashed asset: index.html with 200.
  await page.route(/\/assets\/Report-[^/]*\.js$/, (route) =>
    route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><html><body>stale</body></html>' })
  );

  await page.goto('/report');

  const alert = page.getByRole('alert');
  await expect(alert).toContainText('This section hit an error', { timeout: 20_000 });
  await expect(page.getByText('Something went wrong')).toHaveCount(0);
  const back = page.getByRole('link', { name: 'Back to dashboard' });
  await expect(back).toBeVisible();

  await back.click();
  await expect(page).toHaveURL(/\/app$/);
  await expect(page.getByText('Smart Strategies')).toBeVisible({ timeout: 20_000 });
  expect(await storedBudget(page)).toBe(BUDGET);
});

test('a malformed AI reply keeps the dashboard alive', async ({ page }) => {
  await seed(page);
  await mockGateway(page, { text: { not: 'a string' }, toolCalls: 'nope', raw: 5 });

  await page.goto('/app');
  await expect(page.getByText('Smart Strategies')).toBeVisible({ timeout: 20_000 });

  const input = page.getByPlaceholder(/Forex broker/);
  await expect(input).toBeVisible({ timeout: 10_000 });
  await input.fill('Casino operator, 50k per month, Germany');
  await input.press('Enter');

  await expect(page.getByText('Thinking')).toHaveCount(0, { timeout: 15_000 });
  await expect(page.getByText('CRASH DETECTED')).toHaveCount(0);
  await expect(page.getByText('Something went wrong')).toHaveCount(0);
  await expect(page.getByText('This section hit an error')).toHaveCount(0);
  await expect(page.getByText('Smart Strategies')).toBeVisible();
  expect(await storedBudget(page)).toBe(BUDGET);
});

for (const [route, marker] of [
  ['/report', 'Before You Launch'],
  ['/output', 'Generated by MediaPlanner Pro'],
]) {
  test(`${route} renders on the production build with a mocked narrative`, async ({ page }) => {
    await seed(page);
    await mockGateway(page, { text: JSON.stringify(NARRATIVE), toolCalls: [], raw: [] });

    await page.goto(route);
    await expect(page.getByText(marker)).toBeVisible({ timeout: 30_000 });
    await expect(page.getByText(NARRATIVE.biggestRisk).first()).toBeVisible({ timeout: 15_000 });
    await expect(page.getByText('Something went wrong')).toHaveCount(0);
    await expect(page.getByText('This section hit an error')).toHaveCount(0);
  });
}

test('/sw.js is the kill-switch and no service worker is registered', async ({ page, request }) => {
  const res = await request.get('/sw.js');
  expect(res.status()).toBe(200);
  const body = await res.text();
  expect(body).not.toMatch(/addEventListener\(\s*['"]fetch['"]/);
  expect(body).toContain('unregister');

  await seed(page);
  await page.goto('/app');
  await page.waitForLoadState('load');
  await page.waitForTimeout(500);
  const count = await page.evaluate(async () => (await navigator.serviceWorker.getRegistrations()).length);
  expect(count).toBe(0);
});

test('hidden sourcemaps: no .map is deployed or served, the maps live in .sourcemaps', async ({ request }) => {
  const dist = path.resolve('dist-qa');
  const listMaps = (dir: string): string[] =>
    fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
      e.isDirectory() ? listMaps(path.join(dir, e.name)) : e.name.endsWith('.map') ? [e.name] : []
    );
  expect(listMaps(dist)).toEqual([]);
  const stored = fs.readdirSync(path.resolve('.sourcemaps')).filter((f) => f.endsWith('.js.map'));
  expect(stored.length).toBeGreaterThan(0);

  const assets = fs.readdirSync(path.join(dist, 'assets')).filter((f) => f.endsWith('.js'));
  expect(assets.length).toBeGreaterThan(0);
  for (const file of assets.slice(0, 5)) {
    // The preview server falls back to index.html for unknown paths (Vercel returns 404 via vercel.json),
    // so assert that no source map content is ever served.
    const res = await request.get(`/assets/${file}.map`);
    const body = await res.text();
    expect(body).not.toContain('"mappings"');
    expect(body).not.toContain('"sourcesContent"');
    expect([404, 200]).toContain(res.status());
    if (res.status() === 200) expect(res.headers()['content-type']).toContain('text/html');
  }
  // Every built chunk has a hidden map, and the bundle carries no sourceMappingURL comment.
  for (const file of assets.slice(0, 5)) {
    expect(stored).toContain(`${file}.map`);
    expect(fs.readFileSync(path.join(dist, 'assets', file), 'utf8')).not.toContain('sourceMappingURL');
  }
});

test('a forced crash reports to /api/client-error and offers a real exit', async ({ page }) => {
  await seed(page);
  await mockGateway(page, { text: JSON.stringify(NARRATIVE), toolCalls: [], raw: [] });
  await page.route(/\/assets\/Report-[^/]*\.js$/, (route) =>
    route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><html><body>stale</body></html>' })
  );
  const reports: Record<string, unknown>[] = [];
  await page.route('**/api/client-error', (route) => {
    reports.push(JSON.parse(route.request().postData() ?? '{}'));
    return route.fulfill({ status: 204 });
  });
  // Unrelated storage that must never end up in a debug export.
  await page.addInitScript(() => localStorage.setItem('__clerk_db_jwt', 'must-not-leak'));

  await page.goto('/report');
  await expect(page.getByRole('alert')).toContainText('This section hit an error', { timeout: 20_000 });
  await expect(page.getByText('CRASH DETECTED')).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Back to dashboard' })).toBeVisible();

  await expect.poll(() => reports.some((r) => r.section === 'route:/report'), { timeout: 10_000 }).toBe(true);
  const report = reports.find((r) => r.section === 'route:/report')!;
  expect(typeof report.buildId).toBe('string');
  expect(String(report.buildId).length).toBeGreaterThan(0);
  expect(String(report.stack).length).toBeGreaterThan(0);
  expect(String(report.componentStack).length).toBeGreaterThan(0);
  expect(report.url).toBe('/report');

  const [download] = await Promise.all([
    page.waitForEvent('download'),
    page.getByRole('button', { name: 'Export debug state' }).click(),
  ]);
  expect(download.suggestedFilename()).toMatch(/^mediaplanner-debug-.+\.json$/);
  const file = await download.path();
  const exported = JSON.parse(fs.readFileSync(file, 'utf8'));
  const allowed = [
    'mediaplan-store-v2',
    'multi-month-plan-store',
    'mediaplan-planner-chat-v1',
    'mediaplan-crash-backup',
    'mediaplan-pre-apply-backup',
  ];
  for (const key of Object.keys(exported.storage)) expect(allowed).toContain(key);
  expect(JSON.stringify(exported)).not.toContain('must-not-leak');
  expect(exported.buildId).toBe(report.buildId);
  expect(exported.url).toBe('/report');
});
